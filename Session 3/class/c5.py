# j --> 1 2 3 4 5 (int)
for j in range(1, 6, 1):
    # 1 3 5
    if j % 2 != 0:
        # "1" * 1 -> "1"
        # "3" * 3 -> "333"
        # "5" * 5 -> "55555"
        print( str(j) * j )
        # str(5) * 5

# j --> 1 2 3 4 5
for j in range(1, 6, 2):
    # "1" * 1
    # "3" * 3
    # "5" * 5
    print(str(j) * j)



